#ifndef SOMEWM_PAINT_SHADERS_H
#define SOMEWM_PAINT_SHADERS_H

/* All programs fit radii by the CSS border-radius rule and use a one pixel
 * smoothstep on each corner arc. */

static const char paint_shader_vertex[] =
    "attribute vec2 position;\n"
    "attribute vec2 local;\n"
    "attribute vec2 uv;\n"
    "varying vec2 v_pos;\n"
    "varying vec2 v_texcoord;\n"
    "void main() {\n"
    "    gl_Position = vec4(position, 0.0, 1.0);\n"
    "    v_pos = local;\n"
    "    v_texcoord = uv;\n"
    "}\n";

static const char paint_shader_common[] =
    "#ifdef GL_FRAGMENT_PRECISION_HIGH\n"
    "precision highp float;\n"
    "#else\n"
    "precision mediump float;\n"
    "#endif\n"
    "varying vec2 v_pos;\n"
    "varying vec2 v_texcoord;\n"
    "uniform vec2 size;\n"
    "uniform vec4 radii;\n"
    "uniform int clip_count;\n"
    "uniform vec4 clip_boxes[4];\n"
    "uniform vec4 clip_radii[4];\n"
    "uniform bool masked;\n"
    "uniform sampler2D mask_tex;\n"
    "uniform vec4 mask_box;\n"
    "vec4 fit_radii(vec2 box, vec4 r) {\n"
    "\tfloat f = 1.0;\n"
    "\tif (r.x + r.y > box.x) f = min(f, box.x / (r.x + r.y));\n"
    "\tif (r.w + r.z > box.x) f = min(f, box.x / (r.w + r.z));\n"
    "\tif (r.x + r.w > box.y) f = min(f, box.y / (r.x + r.w));\n"
    "\tif (r.y + r.z > box.y) f = min(f, box.y / (r.y + r.z));\n"
    "\treturn r * f;\n"
    "}\n"
    "\n"
    "float arc_alpha(vec2 d, float r) {\n"
    "\treturn r > 0.0 ? 1.0 - smoothstep(-0.5, 0.5, length(max(d, 0.0)) - r) : 1.0;\n"
    "}\n"
    "\n"
    "float corner_alpha(vec2 p, vec2 box, vec4 r) {\n"
    "\tr = fit_radii(box, r);\n"
    "\tvec2 inside = min(p, box - p);\n"
    "\tfloat alpha = smoothstep(-0.5, 0.5, min(inside.x, inside.y));\n"
    "\talpha *= arc_alpha(vec2(r.x - p.x, r.x - p.y), r.x);\n"
    "\talpha *= arc_alpha(vec2(p.x - box.x + r.y, r.y - p.y), r.y);\n"
    "\talpha *= arc_alpha(vec2(p.x - box.x + r.z, p.y - box.y + r.z), r.z);\n"
    "\talpha *= arc_alpha(vec2(r.w - p.x, p.y - box.y + r.w), r.w);\n"
    "\treturn alpha;\n"
    "}\n"
    "\n"
    "float round_coverage(vec2 p) {\n"
    "\tfloat coverage = corner_alpha(p, size, radii);\n"
    "\tfor (int i = 0; i < 4; i++) {\n"
    "\t\tif (i >= clip_count) {\n"
    "\t\t\tbreak;\n"
    "\t\t}\n"
    "\t\tcoverage *= corner_alpha(p - clip_boxes[i].xy, clip_boxes[i].zw, clip_radii[i]);\n"
    "\t}\n"
    "\treturn coverage;\n"
    "}\n"
    "\n"
    "float mask_coverage(vec2 p) {\n"
    "    if (!masked) return 1.0;\n"
    "    vec2 uv = (p - mask_box.xy) / mask_box.zw;\n"
    "    if (uv.x < 0.0 || uv.y < 0.0 || uv.x >= 1.0 || uv.y >= 1.0) return 0.0;\n"
    "    return texture2D(mask_tex, uv).a;\n"
    "}\n";

static const char paint_shader_rect[] =
    "uniform vec4 color;\n"
    "uniform vec4 cutout_box;\n"
    "uniform vec4 cutout_radii;\n"
    "void main() {\n"
    "    vec2 p = v_pos * size;\n"
    "    float coverage = round_coverage(p);\n"
    "    if (cutout_box.z > 0.0) {\n"
    "        coverage *= 1.0 - corner_alpha(p - cutout_box.xy, cutout_box.zw, cutout_radii);\n"
    "    }\n"
    "    gl_FragColor = color * coverage * mask_coverage(p);\n"
    "}\n";

static const char paint_shader_texture[] =
    "uniform float alpha;\n"
    "#ifdef EXTERNAL\n"
    "uniform samplerExternalOES tex;\n"
    "#else\n"
    "uniform sampler2D tex;\n"
    "#endif\n"
    "void main() {\n"
    "    vec4 c = texture2D(tex, v_texcoord);\n"
    "#ifdef OPAQUE\n"
    "    c.a = 1.0;\n"
    "#endif\n"
    "    gl_FragColor = c * alpha * round_coverage(v_pos * size) * mask_coverage(v_pos * size);\n"
    "}\n";

static const char paint_shader_shadow[] =
    "uniform vec4 color;\n"
    "uniform float blur;\n"
    "float rounded_distance(vec2 p) {\n"
    "    vec4 r = fit_radii(size, radii);\n"
    "    vec2 q = abs(p - size * 0.5) - size * 0.5;\n"
    "    float d = length(max(q, 0.0)) + min(max(q.x, q.y), 0.0);\n"
    "    if (r.x > 0.0) d = max(d, length(max(vec2(r.x-p.x, r.x-p.y), 0.0))-r.x);\n"
    "    if (r.y > 0.0) d = max(d, length(max(vec2(p.x-size.x+r.y, r.y-p.y), 0.0))-r.y);\n"
    "    if (r.z > 0.0) d = max(d, length(max(vec2(p.x-size.x+r.z, p.y-size.y+r.z), 0.0))-r.z);\n"
    "    if (r.w > 0.0) d = max(d, length(max(vec2(r.w-p.x, p.y-size.y+r.w), 0.0))-r.w);\n"
    "    return d;\n"
    "}\n"
    "void main() {\n"
    "    vec2 p = v_pos * size;\n"
    "    float d = rounded_distance(p);\n"
    "    float coverage = blur > 0.0 ? 1.0 - smoothstep(0.0, blur, d)\n"
    "        : 1.0 - smoothstep(-0.5, 0.5, d);\n"
    "    for (int i = 0; i < 4; i++) {\n"
    "        if (i >= clip_count) break;\n"
    "        coverage *= corner_alpha(p - clip_boxes[i].xy, clip_boxes[i].zw, clip_radii[i]);\n"
    "    }\n"
    "    gl_FragColor = color * coverage;\n"
    "}\n";

#endif
